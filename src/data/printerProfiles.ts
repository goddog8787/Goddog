// Helper to get printers belonging to a specific brandId
export function getPrintersByBrand(brandId: string): PrinterProfile[] {
  if (!brandId || brandId === 'all') return PRINTER_PROFILES;
  return PRINTER_PROFILES.filter(
    (p) =>
      p.brandId === brandId ||
      p.brand.toLowerCase().includes(brandId.toLowerCase()) ||
      p.id.toLowerCase().startsWith(brandId.toLowerCase())
  );
}

// Helper to get profile by ID or partial match (supports model names like "SparkX i8", "H3C", "K3", "Infimech MX Pro", "Ender-3", etc.)
export function findPrinterProfile(queryOrId: string): PrinterProfile {
  if (!queryOrId) return PRINTER_PROFILES[1]; // Default Bambu X1C
  const normalized = queryOrId.trim().toLowerCase();

  const directMatch = PRINTER_PROFILES.find((p) => p.id.toLowerCase() === normalized);
  if (directMatch) return directMatch;

  // Check exact keyword tokens for popular queries like "i8", "h3c", "k3", "k2", "mx pro", "ender-3"
  const tokenMatch = PRINTER_PROFILES.find(
    (p) =>
      p.name.toLowerCase().includes(normalized) ||
      normalized.includes(p.name.toLowerCase()) ||
      normalized.includes(p.id.toLowerCase())
  );
  if (tokenMatch) return tokenMatch;

  // Fallback token scoring
  const words = normalized.split(/[\s/\-_()]+/).filter(Boolean);
  let bestProfile = PRINTER_PROFILES[1];
  let bestScore = 0;
  for (const profile of PRINTER_PROFILES) {
    const haystack = `${profile.id} ${profile.brand} ${profile.series} ${profile.name}`.toLowerCase();
    let score = 0;
    for (const w of words) {
      if (haystack.includes(w)) score += w.length;
    }
    if (score > bestScore) {
      bestScore = score;
      bestProfile = profile;
    }
  }

  return bestProfile;
}
